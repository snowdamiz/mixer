#!/usr/bin/env python3
"""Generate the UP5 support table from the checked-out compiler and host replay."""

import argparse
from collections import Counter
import json
from pathlib import Path
import shlex
import subprocess
import sys


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
RUNNER = HERE.parent / "HostReplay" / "run.sh"
TABLE = HERE.parent / "support-table.md"
DUAL_COMPILE = "PASS identical shared sources compile for iOS 17.0 with MixerSwiftUI and Apple SwiftUI"
UNSUPPORTED_CALLS = "PASS unsupported authoring calls compile with Apple SwiftUI and fail with MixerSwiftUI"


def run(mode):
    command = [str(RUNNER.relative_to(ROOT)), mode]
    print(shlex.join(command), flush=True)
    result = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE, text=True)
    print(result.stdout, end="", flush=True)
    result.check_returncode()
    return result.stdout


def require_passes(mode, output, expected):
    counts = Counter(output.splitlines())
    for line in expected:
        if counts[line] != 1:
            raise ValueError(f"{mode} must report exactly one {line!r} (found {counts[line]})")


def render(catalog, ios_output, host_output):
    replays = catalog["replays"]
    require_passes("iOS compile", ios_output, (DUAL_COMPILE, UNSUPPORTED_CALLS))
    require_passes("macOS host replay", host_output, (replay["pass"] for replay in replays.values()))

    header = (
        "Construct", "Exercised scope", "Apple SwiftUI iOS 17 compile", "MixerSwiftUI iOS 17 compile",
        "macOS SDK replay", "iOS renderer mapping", "Compose mapping", "iOS guest", "Android guest", "GC4",
    )
    lines = [
        "# MixerSwiftUI support table",
        "",
        "<!-- Generated by SupportTable/generate.py. Edit the catalog and rerun the checks. -->",
        "",
        "The iPhoneOS SDK compiles each shared fixture for iOS 17.0 in both modes. Shared source uses",
        "`import SwiftUI`. The Mixer build aliases that import to `MixerSwiftUI`. The host replay",
        "checks SDK documents, state, identity, and event routing in a macOS process.",
        "",
        "Pending means this suite has yet to verify that mode. GC4 requires a matching iOS Apple",
        "differential run for Apple-equivalent constructs, or native-versus-update behavior on both",
        "platforms for Mixer-only constructs.",
        "",
        "Run the generator from the checkout root. Add `--check` to rerun the tests and compare the",
        "generated bytes with the checked-in table.",
        "",
        "```sh",
        f"python3 -B {Path(__file__).resolve().relative_to(ROOT)}",
        "```",
        "",
        "| " + " | ".join(header) + " |",
        "| " + " | ".join(["---"] * len(header)) + " |",
    ]
    for construct in catalog["constructs"]:
        tests = [replays[name] for name in construct["tests"]]
        sources = sorted({test["source"] for test in tests})
        compile_links = ", ".join(f"[{Path(source).stem}](HostReplay/{source})" for source in sources)
        host_links = ", ".join(f"[`{test['function']}`](HostReplay/{test['test']})" for test in tests)
        row = [construct["name"], construct["scope"], f"Pass · {compile_links}", "Pass", f"Pass · {host_links}"]
        # Renderer, guest, and GC4 results require their own executable evidence.
        lines.append("| " + " | ".join(row + ["Pending"] * 5) + " |")

    lines += [
        "",
        "The iOS compile run also verifies that Apple SwiftUI accepts each marked call and",
        "MixerSwiftUI rejects it. [Unsupported control fixtures](HostReplay/UnsupportedControls.swift)",
        "",
    ]
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the committed table without writing it")
    args = parser.parse_args()
    try:
        catalog = json.loads((HERE / "cases.json").read_text(encoding="utf-8"))
        generated = render(catalog, run("ios"), run("debug"))
        if args.check:
            if TABLE.read_bytes() != generated:
                raise ValueError("support-table.md is stale. Rerun the generator without --check.")
        else:
            TABLE.write_bytes(generated)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"{error}\n")
    print(f"{'Verified' if args.check else 'Generated'} {TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
