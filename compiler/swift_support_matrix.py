#!/usr/bin/env python3
"""Generate or check the public Swift language support matrix."""

import argparse
from pathlib import Path
import re

from qualification_support import strict_json

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "swift-language-support.json"
OUTPUT = HERE / "swift-language-support.md"
COMMANDS = Path("Fixtures/FeatureProbe/README.md")
LABEL_SCOPE = {
    "native supported": "native",
    "guest supported": "owned",
    "host bridge required": "owned",
    "unsupported": "owned",
}


def render():
    manifest = strict_json(MANIFEST.read_text(encoding="utf-8"))
    checks = manifest["checks"]
    headings = re.findall(r"^## ([^\n]+)$", (HERE / COMMANDS).read_text(encoding="utf-8"), re.M)
    anchors = {heading.lower().replace(" ", "-") for heading in headings}
    for name, check in checks.items():
        if check["anchor"] not in anchors or check["scope"] not in {"native", "owned", "development"}:
            raise ValueError(f"invalid test command reference: {name}")

    lines = [
        "# Swift language support",
        "",
        "<!-- Generated by compiler/swift_support_matrix.py from swift-language-support.json. -->",
        "",
        "The labels apply to the tested operation and environment in each row. An",
        "unqualified row has no support label. The owned rows cover a macOS host",
        "with the compact VM or the named opt-in VM fixtures. Device, signed",
        "activation, and whole-language qualification remain separate.",
        "",
        "- **native supported.** The cited behavior ran in native Swift on macOS.",
        "- **guest supported.** The cited Swift guest ran in the owned VM on macOS.",
        "- **host bridge required.** The operation uses an explicit typed capability boundary.",
        "- **unsupported.** The cited execution or admission boundary rejects the scoped case.",
        "",
        "| Feature | Support label | Tested scope or gap | Positive control | Negative or edge control | Related evidence |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    seen = set()
    for row in manifest["rows"]:
        feature, label, scope = (row[key] for key in ("feature", "label", "scope"))
        if feature in seen or any(not text or "|" in text or "\n" in text for text in (feature, scope)):
            raise ValueError(f"invalid or duplicate row: {feature}")
        seen.add(feature)
        positive, negative, related = (row.get(key, []) for key in ("positive", "negative", "related"))
        if label is None:
            if positive or negative:
                raise ValueError(f"put partial evidence in related evidence for {feature}")
        elif label not in LABEL_SCOPE or any(
            not names or {checks[name]["scope"] for name in names} != {LABEL_SCOPE[label]}
            for names in (positive, negative)
        ):
            raise ValueError(f"{feature} needs positive and negative controls for {label}")

        def links(names):
            return ", ".join(
                f"[{checks[name]['title']}]({COMMANDS.as_posix()}#{checks[name]['anchor']})"
                for name in names
            ) or "—"

        cells = (feature.replace("<", "&lt;"), label or "Unqualified", scope,
                 links(positive), links(negative), links(related))
        lines.append(f"| {' | '.join(cells)} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the checked-in matrix is stale")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            parser.exit(1, "Swift support matrix is stale. Run python3 -B compiler/swift_support_matrix.py\n")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
