const TEST: &str = "bulk_memory_matches_node";
const CASE_ENV: &str = "MIXER_DIFFERENTIAL_BULK_CASE";

#[derive(Clone, Copy)]
enum Bulk {
    Copy(i32),
    Fill(i32),
}

struct Case {
    name: &'static str,
    operation: Bulk,
    destination: i32,
    length: i32,
    traps: bool,
}

const fn copy(name: &'static str, dst: i32, src: i32, len: i32, traps: bool) -> Case {
    Case {
        name,
        operation: Bulk::Copy(src),
        destination: dst,
        length: len,
        traps,
    }
}

const fn fill(name: &'static str, dst: i32, value: i32, len: i32, traps: bool) -> Case {
    Case {
        name,
        operation: Bulk::Fill(value),
        destination: dst,
        length: len,
        traps,
    }
}

const CASES: [Case; 16] = [
    copy("overlap-right", 163, 160, 29, false),
    copy("overlap-left", 160, 163, 29, false),
    copy("self-copy", 160, 160, 40, false),
    copy("source-exact-end", 160, 65528, 8, false),
    copy("destination-exact-end", 65528, 160, 8, false),
    fill("positive-low-byte", 165, 0x1234, 17, false),
    fill("negative-low-byte-exact-end", 65528, -1, 8, false),
    fill("truncated-to-zero", 160, 256, 40, false),
    copy("zero-copy-valid-end", 65536, 65536, 0, false),
    fill("zero-fill-valid-end", 65536, -1, 0, false),
    copy("zero-copy-destination-oob", 65537, 160, 0, true),
    copy("zero-copy-source-oob", 160, 65537, 0, true),
    fill("zero-fill-oob", 65537, 0, 0, true),
    copy("copy-destination-crosses-end", 65529, 160, 8, true),
    copy("copy-source-crosses-end", 160, 65529, 8, true),
    fill("fill-crosses-end", 65529, 0x1234, 8, true),
];

fn constant(body: &mut Vec<u8>, value: i32) {
    body.push(0x41);
    body.extend(fixture::signed(value));
}

// Original modules use the supported command ABI and one fixed memory page.
// Distinct data and surrounding bytes make overlap direction and fill truncation
// observable through fd_write; the oracle executes these same generated bytes.
fn module(case: &Case) -> Vec<u8> {
    let mut f = fixture::Fixture::default();
    f.function_types = vec![34];
    f.memory = vec![1, 1, 1, 1];
    f.table = vec![1, 0x70, 1, 1, 1];
    f.exports = vec![(b"memory".to_vec(), 2, 0), (b"_start".to_vec(), 0, 34)];
    let fd_write = f
        .imports
        .iter()
        .position(|(_, field, _, _)| field == b"fd_write")
        .unwrap();
    let mut body = vec![0];
    constant(&mut body, case.destination);
    constant(
        &mut body,
        match case.operation {
            Bulk::Copy(src) => src,
            Bulk::Fill(value) => value,
        },
    );
    constant(&mut body, case.length);
    match case.operation {
        Bulk::Copy(_) => body.extend([0xfc, 10, 0, 0]),
        Bulk::Fill(_) => body.extend([0xfc, 11, 0]),
    }
    for pointer in [0, 8] {
        for value in [1, pointer, 1, 24] {
            constant(&mut body, value);
        }
        body.push(0x10);
        body.extend(fixture::uint(fd_write as u32));
        body.push(0x1a);
    }
    body.push(0x0b);
    f.bodies = vec![body];
    let mut iovecs = vec![];
    for value in [160u32, 40, 65528, 8] {
        iovecs.extend(value.to_le_bytes());
    }
    f.data = vec![
        fixture::data_segment(0, &iovecs),
        fixture::data_segment(160, b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcd"),
        fixture::data_segment(65528, &[0x80, 0x91, 0xa2, 0xb3, 0xc4, 0xd5, 0xe6, 0xf7]),
    ];
    f.bytes()
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

// Only fd_write is bridged. Node's built-in engine performs the bulk operation.
// No post-trap memory observation is available through the consuming Mixer API.
const ORACLE: &str = r#"
const fs = require('node:fs');
const bytes = Buffer.from(fs.readFileSync(0, 'utf8'), 'hex');
if (!WebAssembly.validate(bytes)) throw new Error('REJECTION stage=node-validation');
const m = new WebAssembly.Module(bytes);
const wasi = Object.fromEntries(WebAssembly.Module.imports(m).map(x =>
  [x.name, () => { throw new Error('unexpected import ' + x.name); }]));
let instance; const output = [];
wasi.fd_write = (fd, ptr, count, written) => {
  if (fd !== 1 || count !== 1) throw new Error('unexpected output ABI');
  const memory = instance.exports.memory.buffer, view = new DataView(memory);
  const begin = view.getUint32(ptr, true), size = view.getUint32(ptr + 4, true);
  output.push(Buffer.from(new Uint8Array(memory, begin, size)));
  view.setUint32(written, size, true); return 0;
};
instance = new WebAssembly.Instance(m, {wasi_snapshot_preview1: wasi});
let terminal = 'value';
try { instance.exports._start(); }
catch (e) {
  if (!(e instanceof WebAssembly.RuntimeError) || !/out of bounds/i.test(e.message)) throw e;
  terminal = 'memory_out_of_bounds';
}
console.log(terminal + ':' + Buffer.concat(output).toString('hex'));
"#;

fn isolated_bulk_case(index: usize) {
    let case = CASES.get(index).expect("bulk case must be in 0..16");
    let bytes = module(case);
    println!("MODULE case={index} name={} hex={}", case.name, hex(&bytes));
    let mut oracle = Command::new(std::env::var_os("MIXER_NODE").unwrap_or_else(|| "node".into()))
        .current_dir(std::env::current_dir().unwrap())
        .args(["-e", ORACLE])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("explicit development oracle requires Node");
    let write = oracle
        .stdin
        .take()
        .unwrap()
        .write_all(hex(&bytes).as_bytes());
    let output = oracle.wait_with_output().unwrap();
    write.unwrap();
    assert!(
        output.status.success(),
        "Node stage failure case={index}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(output.stderr.is_empty());
    let oracle_line = String::from_utf8(output.stdout).unwrap();
    let oracle_line = oracle_line.trim();
    let (terminal, observed) = oracle_line
        .split_once(':')
        .expect("Node terminal and bytes");
    assert_eq!(
        terminal,
        if case.traps {
            "memory_out_of_bounds"
        } else {
            "value"
        },
        "Node case={index}"
    );
    assert_eq!(observed.len(), if case.traps { 0 } else { 48 * 2 });
    println!("ORACLE case={index} {oracle_line}");

    let proof = validate_swift_command(
        &bytes,
        SwiftValidationBudget::default(),
        &Cancellation::default(),
    )
    .unwrap_or_else(|failure| panic!("REJECTION stage=mixer-validation case={index}: {failure:?}"));
    println!("ADMITTED case={index} stage=mixer-validation");
    let mut stdout = vec![];
    let mut stderr = vec![];
    let report = execute_swift_command(
        proof,
        SwiftRunBudget::default(),
        WasiGrants {
            stdout: true,
            ..Default::default()
        },
        WasiBudget::default(),
        Cancellation::default(),
        &mut stdout,
        &mut stderr,
    );
    assert!(
        report.cleanup_completed,
        "UNKNOWN consuming cleanup case={index}: {report:?}"
    );
    let u = report.after_cleanup.expect("terminal consuming usage");
    let r = u.reservations;
    let l = u.live;
    let currents = [
        r.retained_source.current,
        r.retained_metadata.current,
        r.cache.current,
        r.state.current,
        r.wasi.current,
        r.shared.current,
        r.construction.current,
        r.combined.current,
        l.cache_entries.current,
        l.active_pins.current,
        l.frames.current,
        l.values.current,
        l.controls.current,
        l.memory_pages.current,
    ];
    assert_eq!(
        currents, [0; 14],
        "UNKNOWN reservation cleanup case={index}"
    );
    assert_eq!(
        r.live_tickets, 0,
        "UNKNOWN reservation tickets case={index}"
    );
    assert!(
        u.cleanup_invariant.is_none(),
        "UNKNOWN cleanup invariant case={index}"
    );
    println!(
        "CLEANUP case={index} currents={currents:?} tickets={} invariant=none",
        r.live_tickets
    );
    if case.traps {
        let failure = report
            .terminal
            .expect("execution trap, not validation rejection");
        assert_eq!(failure.kind, SwiftRunFailureKind::GuestTrap, "{failure:?}");
        assert_eq!(
            failure.code, "memory_out_of_bounds",
            "case={index}: {failure:?}"
        );
        assert!(!report.succeeded());
    } else {
        assert!(report.succeeded(), "case={index}: {report:?}");
        assert!(report.terminal.is_none());
    }
    assert!(!report.output_error);
    assert_eq!(hex(&stdout), observed, "case={index} name={}", case.name);
    assert!(stderr.is_empty());
    assert_eq!(
        report.calls_by_function.iter().sum::<u64>(),
        if case.traps { 0 } else { 2 }
    );
    println!(
        "PARITY case={index} name={} terminal={terminal} bytes={}",
        case.name,
        hex(&stdout)
    );
}

#[test]
#[ignore = "development Node oracle; run explicitly with experimental-swift-reactor"]
fn bulk_memory_matches_node() {
    match std::env::var(CASE_ENV) {
        Ok(case) => {
            isolated_bulk_case(case.parse().expect("bulk case must be an integer"));
            return;
        }
        Err(std::env::VarError::NotPresent) => {}
        Err(error) => panic!("invalid bulk case: {error}"),
    }
    for case in 0..CASES.len() {
        let output = Command::new(std::env::current_exe().unwrap())
            .current_dir(std::env::current_dir().unwrap())
            .args([
                "--ignored",
                "--exact",
                TEST,
                "--nocapture",
                "--test-threads=1",
            ])
            .env(CASE_ENV, case.to_string())
            .output()
            .unwrap();
        print!("{}", String::from_utf8_lossy(&output.stdout));
        assert!(
            output.status.success(),
            "case={case}: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(stdout.contains(&format!("CLEANUP case={case} ")));
        assert!(stdout.contains(&format!("PARITY case={case} ")));
    }
    println!("16 original bulk-memory cases matched Node; each consumed fourteen zero currents and zero tickets");
}
