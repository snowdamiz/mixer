#!/usr/bin/env python3
"""Emit explicit schema2 Swift identity data from a verified schema2 declared-input snapshot.

The generated source must be included by the native build. This command neither
runs a compiler nor attests the complete build graph, signing, or provenance.
"""
import argparse
import base64
import json
from pathlib import Path
import shutil
import subprocess

import capability_capture as capture


def swift_source(descriptor, fingerprint):
    # No descriptor text, manifest name or path becomes Swift syntax. The fixed
    # symbol and alphabet-only base64 literal avoid escaping/injection ambiguity.
    capture.require(capture.HEX.fullmatch(fingerprint), "invalid embedded fingerprint")
    capture.require(len(descriptor) <= capture.MAX_DESCRIPTOR, "descriptor size limit")
    encoded = base64.b64encode(descriptor).decode("ascii")
    return ('''// Generated by Mixer from a verified schema2 declared-input snapshot.
// Include this source in the native application. This is not build attestation.
import Foundation
import MixerRuntimeIdentity

public enum MixerInstalledCapabilityRuntime {
    public static let fingerprint = "''' + fingerprint + '''"

    public enum LoadError: Error { case encoding, fingerprintMismatch }

    /// Validates the compiled bytes and binds all represented runtime policy.
    /// Failure must keep guest activation disabled; never substitute another file.
    public static func load() throws -> CapabilityRuntimeIdentity {
        guard let bytes = Data(base64Encoded: descriptorBase64) else {
            throw LoadError.encoding
        }
        let identity = try CapabilityRuntimeIdentity(json: bytes)
        guard identity.fingerprint == fingerprint else {
            throw LoadError.fingerprintMismatch
        }
        return identity
    }

    private static let descriptorBase64 = "''' + encoded + '''"
}
''').encode("utf-8")


def emit(snapshot, expected_fingerprint, tool, output):
    checked, descriptor = capture.verified_descriptor(snapshot, expected_fingerprint, tool)
    source = swift_source(descriptor, checked["fingerprint"])
    output = Path(output).absolute()
    output.mkdir(mode=0o700, parents=False, exist_ok=False)
    try:
        capture.write_new(output / "MixerInstalledCapabilityRuntime.swift", source)
        receipt = {
            "schema": 2,
            "identity_schema": 2,
            "fingerprint": checked["fingerprint"],
            "snapshot_sha256": checked["snapshotSHA256"],
            "descriptor_sha256": capture.sha(descriptor),
            "source_sha256": capture.sha(source),
            "source_bytes": len(source),
            "build_attested": False,
            "complete_graph_proven": False,
            "compiled": False,
            "signed": False,
        }
        # Completion receipt last. A failed invocation removes only its own
        # exclusively created directory; an existing user path is untouched.
        capture.write_new(output / "embedding.json", capture.canonical(receipt))
        capture.sync_directory(output)
        capture.sync_directory(output.parent)
        return receipt
    except BaseException:
        shutil.rmtree(output)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ["snapshot", "expected-fingerprint", "identity-tool", "output"]:
        parser.add_argument("--" + name, required=True)
    args = parser.parse_args()
    try:
        result = emit(args.snapshot, args.expected_fingerprint, args.identity_tool, args.output)
        print(json.dumps(result, sort_keys=True))
    except (capture.CaptureError, OSError, subprocess.SubprocessError) as error:
        parser.exit(1, "embedding failed: " + str(error) + "\n")


if __name__ == "__main__":
    main()
