#!/usr/bin/env python3
"""Original hand-encoded Wasm probes for the future public Swift bridge review.

No engine/codec helper is imported. Generated bytes are review inputs, not a
compiled or qualified bridge. The primary fixture's fixed wake polls its own
tokens and advances the storage flow; the native harness never handles a token.
"""
import base64
import hashlib
import json
from pathlib import Path
import sys


def leb(value):
    output = bytearray()
    while True:
        rest = value >> 7
        output.append((value & 127) | (128 if rest else 0))
        value = rest
        if not value:
            return bytes(output)


def signed(value):
    output = bytearray()
    while True:
        part = value & 127
        value >>= 7
        done = (value == 0 and not (part & 64)) or (value == -1 and part & 64)
        output.append(part | (0 if done else 128))
        if done:
            return bytes(output)


def name(value):
    raw = value.encode('utf-8')
    return leb(len(raw)) + raw


def section(tag, raw):
    return bytes([tag]) + leb(len(raw)) + raw


def signature(parameters, results):
    return b'\x60' + leb(len(parameters)) + bytes(parameters) + leb(len(results)) + bytes(results)


def const(value):
    return b'\x41' + signed(value)


def load(address):
    return const(address) + b'\x28\x02\0'


def store(address, expression):
    return const(address) + expression + b'\x36\x02\0'


def call(index):
    return b'\x10' + leb(index)


def condition(expression, instructions):
    return expression + b'\x04\x40' + instructions + b'\x0b'


NAMESPACE = 'bridge_review'
KEY = 'alpha'
BINARY = bytes([0, 1, 2, 3, 255, 254, 128])
I32 = 0x7f
I64 = 0x7e


def arguments(operation, key=KEY, value=None):
    fields = {'namespace': NAMESPACE, 'key': key}
    if operation == 'storage_put':
        fields['valueBase64'] = base64.b64encode(value if value is not None else BINARY).decode()
    return json.dumps(fields, sort_keys=True, separators=(',', ':')).encode()


def module(steps, *, consume=True, burst=1):
    imports = ['storage_get', 'storage_put', 'storage_delete', 'poll']
    types = [signature([], []), signature([I32] * 3, [I32]),
             signature([I64, I32, I32, I32], [I32]), signature([], [I32])]
    # Data regions are disjoint from metadata, tokens and completion buffers.
    segments = []
    data_offset = 1024

    def place(raw):
        nonlocal data_offset
        address = data_offset
        segments.append((address, raw))
        data_offset += len(raw) + 16
        assert data_offset < 2048
        return address, len(raw)

    startup_arguments = place(arguments('storage_put', key='startup_probe'))
    trap_arguments = place(arguments('storage_put', key='trap_probe'))
    recorded_steps = [(operation, *place(raw)) for operation, raw in steps]

    def enqueue(operation, address, length, token=32):
        return const(address) + const(length) + const(token) + call(imports.index(operation))

    def poll(token, output, capacity, length):
        return const(token) + b'\x29\x03\0' + output + const(capacity) + length + call(3)

    # Startup proves effects-disabled terminal bytes through real guest polling.
    startup = store(8, enqueue('storage_put', *startup_arguments, token=24))
    startup += store(12, poll(24, const(2048), 1024, const(16)))
    operation, address, length = recorded_steps[0]
    run = store(0, const(1)) + store(40, enqueue(operation, address, length)) + load(40)
    if burst > 1:
        run = store(0, const(1))
        for index in range(burst):
            run += enqueue(operation, address, length, token=256 + index * 8)
            if index != burst - 1:
                run += b'\x1a'
    wake = store(4, load(4) + const(1) + b'\x6a')
    if consume:
        # stage i => completion bytes at4096+(i-1)*2048, length at64+i*4.
        destination = const(4096) + load(0) + const(1) + b'\x6b' + const(2048) + b'\x6c\x6a'
        length_pointer = const(64) + load(0) + const(4) + b'\x6c\x6a'
        successful_poll = store(0, load(0) + const(1) + b'\x6a')
        for stage, (operation, address, length) in enumerate(recorded_steps[1:], start=2):
            successful_poll += condition(load(0) + const(stage) + b'\x46',
                                         store(40, enqueue(operation, address, length)))
        active = load(0) + const(0) + b'\x4b' + load(0) + const(len(steps) + 1) + b'\x49\x71'
        polling = store(44, poll(32, destination, 1024, length_pointer))
        polling += condition(load(44) + b'\x45', successful_poll)
        wake += condition(active, polling)
    trap = enqueue('storage_put', *trap_arguments) + b'\x1a\x00'
    spin = enqueue('storage_put', *trap_arguments) + b'\x1a\x03\x40\x0c\0\x0b'
    functions = [(0, startup), (0, wake), (3, run), (3, load(0)), (3, load(4)), (0, trap), (0, spin)]
    exports = [('startup', 4), ('mixer_guest_capability_ready_v1', 5),
               ('run', 6), ('stage', 7), ('wakeCount', 8), ('enqueueThenTrap', 9), ('enqueueThenSpin', 10)]
    wasm = b'\0asm\x01\0\0\0' + section(1, leb(len(types)) + b''.join(types))
    wasm += section(2, leb(4) + b''.join(name('mixer.capability.v1') + name(n) + b'\0' + leb(2 if n == 'poll' else 1) for n in imports))
    wasm += section(3, leb(len(functions)) + b''.join(leb(ty) for ty, _ in functions))
    wasm += section(5, b'\x01\x01\x01\x01')  # one defined memory, min=max1
    wasm += section(7, leb(len(exports)) + b''.join(name(n) + b'\0' + leb(index) for n, index in exports))
    bodies = [b'\0' + code + b'\x0b' for _, code in functions]
    wasm += section(10, leb(len(bodies)) + b''.join(leb(len(body)) + body for body in bodies))
    wasm += section(11, leb(len(segments)) + b''.join(b'\0' + const(offset) + b'\x0b' + leb(len(raw)) + raw for offset, raw in segments))
    return wasm


def main():
    destination = Path(sys.argv[1])
    destination.mkdir(parents=True, exist_ok=True)
    flow = [('storage_put', arguments('storage_put')), ('storage_get', arguments('storage_get')),
            ('storage_delete', arguments('storage_delete')), ('storage_get', arguments('storage_get')),
            ('storage_put', arguments('storage_put', value=b'')), ('storage_get', arguments('storage_get')),
            ('storage_delete', arguments('storage_delete'))]
    probes = {
        'storage-flow.wasm': module(flow),
        'single-put.wasm': module([('storage_put', arguments('storage_put'))]),
        'burst-eight.wasm': module([('storage_put', arguments('storage_put'))], consume=False, burst=8),
        'ready-not-consumed.wasm': module([('storage_get', arguments('storage_get'))], consume=False),
        'empty-arguments.wasm': module([('storage_put', b'')]),
        'duplicate-key.wasm': module([('storage_put', b'{"namespace":"bridge_review","namespace":"bridge_review","key":"alpha","valueBase64":""}')]),
        'wrong-operation-object.wasm': module([('storage_put', arguments('storage_get'))]),
        'noncanonical-base64.wasm': module([('storage_put', b'{"namespace":"bridge_review","key":"alpha","valueBase64":"AA"}')]),
    }
    records = []
    for name_, raw in probes.items():
        (destination / name_).write_bytes(raw)
        records.append({'name': name_, 'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()})
    manifest = {'scope': 'Original fixtures only; no bridge execution or qualification',
                'namespace': NAMESPACE, 'key': KEY, 'binary_value_base64': base64.b64encode(BINARY).decode(),
                'flow_steps': len(flow), 'flow_done_stage': len(flow) + 1,
                'metadata': {'stage': 0, 'wake_count': 4, 'startup_enqueue_status': 8,
                             'startup_poll_status': 12, 'startup_length': 16, 'latest_enqueue_status': 40,
                             'latest_wake_poll_status': 44, 'startup_completion': 2048,
                             'step_length': '64 + stage * 4', 'step_completion': '4096 + (stage - 1) * 2048',
                             'completion_capacity': 1024}, 'fixtures': records}
    (destination / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps({'prepared': len(records), 'scope': manifest['scope']}))


if __name__ == '__main__':
    main()
