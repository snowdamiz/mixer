#!/usr/bin/env python3
"""Regenerate the checked-in Swift client for contracts/release-rest-v3.json."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / "contracts/release-rest-v3.json"
OUTPUT = ROOT / "cli/Sources/MixerBuild/GeneratedReleaseRESTV3.swift"
ROUTER = ROOT / "hosted/lib/mixer_hosted_web/router.ex"
PARAMETER = re.compile(r"\{([a-z_0-9]+)\}")
SWIFT_TYPES = {
    "string": "String",
    "uint64": "UInt64",
    "bool": "Bool",
    "base64": "Data",
    "signed-scope": "[String: CanonicalValue]",
}
PATH_CHECKS = {"identifier": "checkedID", "digest": "checkedDigest"}


def swift_name(key):
    first, *rest = key.split("_")
    acronyms = {"id": "ID", "sha256": "SHA256"}
    return first + "".join(acronyms.get(token, token.capitalize()) for token in rest)


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def object_lines(name, fields, conformance, optional_fields=None):
    optional_fields = optional_fields or {}
    suffix = f": {conformance}" if conformance else ""
    lines = [f"    struct {name}{suffix} {{"]
    for key, field_type in (fields | optional_fields).items():
        swift_type = SWIFT_TYPES.get(field_type, field_type)
        nullable = "?" if key in optional_fields else ""
        lines.append(f"        let {swift_name(key)}: {swift_type}{nullable}")
    if conformance:
        lines.extend(["", "        private enum CodingKeys: String, CodingKey {"])
        for key in fields | optional_fields:
            property_name = swift_name(key)
            case = property_name if key == property_name else f"{property_name} = {quoted(key)}"
            lines.append(f"            case {case}")
        lines.append("        }")
    return lines


def request_lines(name, schema, envelopes, records):
    fields = schema["fields"]
    encoding = schema["encoding"]
    if encoding == "json-file":
        lines = object_lines(name, fields, "Encodable")
        lines.extend(["", "        func encodeBody() throws -> Data { try JSONFile.data(self) }"])
    elif encoding == "raw-json-members":
        lines = object_lines(name, fields, "")
        lines.extend(["", "        func encodeBody() throws -> Data {"])
        for index, (key, field_type) in enumerate(fields.items()):
            prefix = ("{" if index == 0 else ",") + quoted(key) + ":"
            property_name = swift_name(key)
            if field_type in envelopes:
                value = f"{property_name}.bytes"
            elif field_type == "base64":
                prefix += '"'
                value = f'{property_name}.base64EncodedData() + Data("\\\"".utf8)'
            elif field_type in records:
                value = f"(try JSONFile.data({property_name}))"
            else:
                raise ValueError(f"unsupported raw JSON member type: {field_type}")
            operator = "            " if index == 0 else "                + "
            lines.append(f"{operator}Data({quoted(prefix)}.utf8) + {value}")
        lines.extend(['                + Data("}".utf8)', "        }"])
    else:
        raise ValueError(f"unsupported request encoding: {encoding}")
    return lines + ["    }", ""]


def path_expression(path, parameters):
    def interpolation(match):
        key = match[1]
        checker = PATH_CHECKS[parameters[key]]
        return f"\\(try ReleaseV3Wire.{checker}({swift_name(key)}))"

    return PARAMETER.sub(interpolation, path)


def operation_lines(name, operation, parameters):
    path = operation["path"]
    arguments = ["_ project: Project"] + [
        f"{swift_name(key)}: String" for key in PARAMETER.findall(path)
    ] + [f"body: {operation['request']}"]
    has_reason = operation.get("cliReasonRequired", False)
    if has_reason:
        arguments.append("reason: String")

    swift_path = path_expression(path, parameters)
    statuses = ", ".join(map(str, operation["success"]))
    return [
        f"    static func {name}({', '.join(arguments)})",
        f"        throws -> ReleaseV3Operation<{operation['response']}> {{",
        "        ReleaseV3Operation(",
        f"            stage: {quoted(name)}, method: {quoted(operation['method'])},",
        f'            path: try project.path() + "{swift_path}",',
        f"            body: try body.encodeBody(), statuses: [{statuses}], reason: {'reason' if has_reason else 'nil'})",
        "    }",
        "",
    ]


def render(contract):
    if contract["version"] != 3:
        raise ValueError("expected the v3 release REST contract")
    lines = [
        "// Generated by cli/release-tools/generate_release_rest_v3.py from contracts/release-rest-v3.json.",
        "import Foundation",
        "import MixerUpdates",
        "",
        "enum ReleaseRESTV3 {",
        f"    static let mediaType = {quoted(contract['mediaType'])}",
        f"    static let signedDocumentMaximumBytes = {contract['signedDocumentMaximumBytes']}",
        f"    static let responseMaximumBytes = {contract['cliResponseMaximumBytes']}",
        "",
        "    struct Project {",
    ]
    for key in PARAMETER.findall(contract["basePath"]):
        lines.append(f"        let {swift_name(key)}: String")

    parameters = contract["pathParameters"]
    project_path = path_expression(contract["basePath"], parameters)
    lines.extend(["", "        fileprivate func path() throws -> String {",
                  f'            "{project_path}"', "        }", "    }", ""])

    for name, field in contract["signedEnvelopes"].items():
        lines.extend([
            f"    enum {name}Envelope: ReleaseV3Envelope {{",
            f"        static let field = {quoted(field)}",
            "    }",
            f"    typealias {name} = ReleaseV3SignedJSON<{name}Envelope>",
            "",
        ])

    for name, schema in contract["requests"].items():
        lines.extend(request_lines(name, schema, contract["signedEnvelopes"], contract["records"]))

    for schemas, conformance in [(contract["records"], "Codable, Equatable"), (contract["responses"], "Decodable")]:
        for name, schema in schemas.items():
            fields = schema["fields"]
            optional_fields = schema.get("optionalFields")
            lines.extend(object_lines(name, fields, conformance, optional_fields))
            if schema.get("closed", False):
                if optional_fields:
                    raise ValueError(f"closed object with optional fields is unsupported: {name}")
                names = ", ".join(quoted(key) for key in fields)
                lines.extend([
                    "",
                    "        init(from decoder: any Decoder) throws {",
                    f"            try ReleaseV3Wire.requireFields([{names}], from: decoder)",
                    "            let values = try decoder.container(keyedBy: CodingKeys.self)",
                ])
                for key, field_type in fields.items():
                    property_name = swift_name(key)
                    swift_type = SWIFT_TYPES.get(field_type, field_type)
                    lines.append(f"            {property_name} = try values.decode({swift_type}.self, forKey: .{property_name})")
                lines.append("        }")
            lines.extend(["    }", ""])

    for name, operation in contract["operations"].items():
        lines.extend(operation_lines(name, operation, parameters))
    return "\n".join(lines[:-1] + ["}", ""]).encode()


def check_router(contract):
    def phoenix(path):
        return PARAMETER.sub(r":\1", path)

    source = ROUTER.read_text(encoding="utf-8")
    scope = phoenix(contract["basePath"])
    block = re.search(rf'^  scope "{re.escape(scope)}" do\n(.*?)^  end$', source, re.M | re.S)
    if not block or "pipe_through(:customer_identity)" not in block[1]:
        raise SystemExit(f"Phoenix customer identity scope missing for {scope}")
    route = re.compile(r'\b([a-z]+)\(\s*"([^"]+)"\s*,\s*MixerHostedWeb\.(\w+)\s*,\s*:(\w+)\s*\)')
    actual = sorted(
        (method.upper(), path, controller, action)
        for method, path, controller, action in route.findall(block[1])
        if method not in {"get", "head", "options"}
    )
    expected = sorted(
        (op["method"], phoenix(op["path"]), op["phoenixController"], name)
        for name, op in contract["operations"].items()
    )
    if actual != expected:
        raise SystemExit(f"Phoenix release routes differ from contract\nExpected: {expected}\nFound: {actual}")
    print(f"Matched {len(expected)} Phoenix router source declarations")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify checked-in Swift output")
    parser.add_argument("--check-router", action="store_true", help="also compare scoped Phoenix router declarations")
    args = parser.parse_args()
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    output = render(contract)
    if args.check or args.check_router:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != output:
            script = Path(__file__).resolve().relative_to(ROOT)
            raise SystemExit(f"Stale generated Swift. Run python3 -B {script}.")
        print(f"Checked {OUTPUT.relative_to(ROOT)}")
    else:
        OUTPUT.write_bytes(output)
    if args.check_router:
        check_router(contract)


if __name__ == "__main__":
    main()
