#!/usr/bin/env python3
"""Freeze this independent review after verifying exact evidence and custody."""
import datetime
import hashlib
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def demand(value, message):
    if not value:
        raise ValueError(message)


def identity(path):
    data = path.read_bytes()
    return {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def load(name):
    return json.loads((HERE / name).read_text())


demand(not (HERE / 'manifest.json').exists(), 'Already sealed')
acceptance = load('acceptance.json')
receipt = load('receipt.json')
demand(receipt['status'] == 'passed-private-host-source-review', 'Main host replay did not pass')
demand(receipt['commands'] == 118 and receipt['owned_scratch_removed'] and receipt['owned_children_reaped'], 'Main run accounting/cleanup')
demand(len(load('commands.json')) == 118 and all(c['child_reaped'] and not c['timed_out'] for c in load('commands.json')), 'Main commands')
demand(len(load('attempt-1/commands.json')) == 8, 'Failed attempt evidence')
demand(load('attempt-1/receipt.json')['status'] == 'failed' and load('attempt-1/receipt.json')['owned_scratch_removed'], 'Retained failure/cleanup')
demand(load('export-comparison.json')['source_only_directories'] == ['Resources'], 'Corrected empty-directory oracle')
for mode in ['normal', 'optimized']:
    result = load('policy-tests-' + mode + '.json')
    demand(result['methods'] == 9 and result['failures'] == result['errors'] == result['skips'] == 0, 'Independent policy methods')
demand(load('current-official-tool-inventory-command.json')['exit'] == 0, 'Official tool observation')
demand(len(load('policy-commands.json')['commands']) == 2, 'Policy command accounting')
for path, expected in load('custody.json')['seals'].items():
    demand(identity(ROOT / path)['sha256'] == expected, 'Referenced seal changed: ' + path)
for path, expected in json.loads((ROOT / 'verification/android-environment-platform-profile4/source-map.json').read_text()).items():
    demand(identity(ROOT / path) == expected, 'Canonical input changed: ' + path)
for kind in ['created_before_authored_variation', 'exported_with_authored_variation']:
    value = load('actual-consumers.json')[kind]
    for name in ['android-build.py', 'descriptor.json']:
        relative = 'Generated/MixerAndroid/' + ('app/assets/MixerAppearanceV2/' if name == 'descriptor.json' else '') + name
        demand(identity(HERE / 'actual-generated' / name) == value[relative], 'Retained actual consumer mismatch: ' + name)
rows = load('refusal-results.json')
demand(rows['fixtures'] == 15 and rows['commands'] == 105, 'Refusal accounting')
demand(all(r['tool_sentinel_unreached'] and r['full_fixture_inventory_unchanged'] and r['output_absent_or_preserved'] for r in rows['rows']), 'Refusal boundary')
files = {}
for path in sorted(HERE.rglob('*')):
    if path.is_file():
        demand(not path.is_symlink(), 'Unexpected review symlink')
        demand('__pycache__' not in path.parts and path.suffix != '.pyc', 'Unexpected generated bytecode')
        files[str(path.relative_to(ROOT))] = identity(path)
value = {'schema': 1, 'at': datetime.datetime.now(datetime.timezone.utc).isoformat(),
         'command': [sys.executable, *sys.argv], 'python': sys.version,
         'scope': 'Independent exact Android profile4 private host/source development review; no native/public/OTA/GA authority',
         'decision': acceptance['decision'], 'candidate_manifest_sha256': acceptance['candidate_manifest_sha256'],
         'candidate_source_map_sha256': acceptance['candidate_source_map_sha256'],
         'members': len(files), 'member_bytes': sum(r['bytes'] for r in files.values()), 'files': files,
         'native_UI_capture_process_inventory_or_Git': False,
         'product_producer_old_packets_or_root_metadata_written': False,
         'owned_children_reaped': True, 'owned_scratch_removed': True,
         'native_runtime_public_V2_OTA_or_GA_authority': False}
(HERE / 'manifest.json').write_text(json.dumps(value, indent=2, sort_keys=True) + '\n')
print(json.dumps({'manifest': str((HERE / 'manifest.json').relative_to(ROOT)), **identity(HERE / 'manifest.json'),
                  'members': len(files), 'member_bytes': value['member_bytes']}))
