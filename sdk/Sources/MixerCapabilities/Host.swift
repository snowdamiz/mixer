import Foundation

public struct CapabilityGrant: Sendable {
    public let capabilityID: String
    public let schemaSHA256: String
    public let permissions: Set<String>
    public let origins: Set<String>
    public let methods: Set<String>
    public let namespaces: Set<String>
    public init(capabilityID: String, schemaSHA256: String, permissions: Set<String>, origins: Set<String> = [], methods: Set<String> = [], namespaces: Set<String> = []) {
        self.capabilityID = capabilityID; self.schemaSHA256 = schemaSHA256; self.permissions = permissions
        self.origins = origins; self.methods = methods; self.namespaces = namespaces
    }
}

public struct CapabilityPolicy: Sendable {
    private let grants: [String: CapabilityGrant]
    public init(installed: [CapabilityGrant], manifest: [CapabilityGrant]) throws {
        func validate(_ values: [CapabilityGrant]) throws -> [String: CapabilityGrant] {
            guard values.count <= 2, Set(values.map(\.capabilityID)).count == values.count else { throw CapabilityWireError.invalid("grant count") }
            for value in values {
                let http = value.capabilityID == CapabilitySchemas.httpID
                let permission = http ? "network.https" : "storage.appPrivate"
                guard (http || value.capabilityID == CapabilitySchemas.storageID),
                      value.schemaSHA256 == (http ? CapabilitySchemas.httpSHA256 : CapabilitySchemas.storageSHA256),
                      value.permissions.isSubset(of: [permission]), value.origins.count <= 32, value.methods.count <= 6, value.namespaces.count <= 32 else { throw CapabilityWireError.invalid("grant") }
                for origin in value.origins { guard try WireRules.origin(origin) == origin else { throw CapabilityWireError.invalid("origin grant") } }
                for method in value.methods { _ = try WireRules.string(["v": .string(method)], "v", rule: "method", maximum: 6) }
                for namespace in value.namespaces { _ = try WireRules.string(["v": .string(namespace)], "v", rule: "identifier", maximum: 64) }
                guard http ? value.namespaces.isEmpty : (value.origins.isEmpty && value.methods.isEmpty) else { throw CapabilityWireError.invalid("grant family") }
            }
            return Dictionary(uniqueKeysWithValues: values.map { ($0.capabilityID, $0) })
        }
        let installed = try validate(installed), manifest = try validate(manifest)
        var intersection: [String: CapabilityGrant] = [:]
        for (id, native) in installed {
            guard let release = manifest[id] else { continue }
            intersection[id] = CapabilityGrant(capabilityID: id, schemaSHA256: native.schemaSHA256,
                permissions: native.permissions.intersection(release.permissions), origins: native.origins.intersection(release.origins),
                methods: native.methods.intersection(release.methods), namespaces: native.namespaces.intersection(release.namespaces))
        }
        grants = intersection
    }
    func permits(_ operation: CapabilityOperation) -> Bool {
        guard let grant = grants[operation.capabilityID] else { return false }
        switch operation {
        case .http(let request): return grant.permissions.contains("network.https") && grant.methods.contains(request.method) && (try? WireRules.origin(request.url)).map(grant.origins.contains) == true
        case .get(let args): return grant.permissions.contains("storage.appPrivate") && grant.namespaces.contains(args.namespace)
        case .put(let args): return grant.permissions.contains("storage.appPrivate") && grant.namespaces.contains(args.namespace)
        case .delete(let args): return grant.permissions.contains("storage.appPrivate") && grant.namespaces.contains(args.namespace)
        }
    }
}

/// One host per originating guest instance. The session is generated by the host;
/// callers cannot select another guest's owner. Reservations consume a fixed quota.
public actor CapabilityHost {
    public typealias HTTPTransport = @Sendable (HTTPRequestArguments) async throws -> HTTPResponse
    public typealias Delivery = @Sendable (Data) -> Void
    private struct Slot: Sendable {
        var generation: UInt32
        var reserved: Bool
        var call: CapabilityCall?
        var delivery: Delivery?
        var terminal = false
        var work: Task<Void, Never>?
        var timer: Task<Void, Never>?
        var deadline: ContinuousClock.Instant?
        #if !os(WASI)
        var exitLease: CapabilityExitLease?
        #endif
    }
    private let session = UUID().uuidString.lowercased()
    private let policy: CapabilityPolicy
    private let http: HTTPTransport?
    private let storage: (any AppPrivateKeyValueServing)?
    #if !os(WASI)
    private let installedAdapters: InstalledCapabilityAdapters?
    #endif
    private let capacity: Int
    private let generationLimit: UInt32
    private let defaultTimeoutMilliseconds: UInt32
    private var slots: [Slot] = []
    private var closed = false
    public init(policy: CapabilityPolicy, maximumRequests: Int = 64, maximumGenerationsPerSlot: UInt32 = .max,
                timeoutMilliseconds: UInt32 = 30000, http: HTTPTransport? = nil, storage: (any AppPrivateKeyValueServing)? = nil) throws {
        guard (1...256).contains(maximumRequests), maximumGenerationsPerSlot > 0, (1...30000).contains(timeoutMilliseconds) else { throw CapabilityWireError.invalid("host limits") }
        self.policy = policy; capacity = maximumRequests; generationLimit = maximumGenerationsPerSlot
        defaultTimeoutMilliseconds = timeoutMilliseconds; self.http = http; self.storage = storage
        #if !os(WASI)
        installedAdapters = nil
        #endif
    }
    #if !os(WASI)
    /// Explicit concrete adapters whose per-request exit can be observed. The
    /// legacy closure/service initializer cannot attest underlying native exit.
    public init(policy: CapabilityPolicy, maximumRequests: Int = 64, maximumGenerationsPerSlot: UInt32 = .max,
                timeoutMilliseconds: UInt32 = 30000, installedAdapters: InstalledCapabilityAdapters) throws {
        guard (1...256).contains(maximumRequests), maximumGenerationsPerSlot > 0, (1...30000).contains(timeoutMilliseconds) else { throw CapabilityWireError.invalid("host limits") }
        self.policy = policy; capacity = maximumRequests; generationLimit = maximumGenerationsPerSlot
        defaultTimeoutMilliseconds = timeoutMilliseconds; http = nil; storage = nil
        self.installedAdapters = installedAdapters
    }

    /// Accepts only a call on an installed-adapter host. A throw accepts neither
    /// work nor an observer. Once accepted, didExit runs once after both dispatch
    /// return and adapter cleanup, including no-I/O failures, close and deinit.
    /// It may run synchronously on the current executor and must return promptly.
    /// This is not a durable-effect rollback or total OS-resource destruction ack.
    public func submitObserved(_ bytes: Data, deliver: @escaping Delivery,
                               didExit: @escaping @Sendable () -> Void) throws {
        guard !closed, installedAdapters != nil else { throw CapabilityWireError.invalid("observed host unavailable") }
        guard case .call(let call) = try CapabilityCodec.decodeInbound(bytes) else { throw CapabilityWireError.invalid("observed call required") }
        try accept(call, deliver: deliver, didExit: didExit)
    }
    #endif
    deinit { for slot in slots { slot.work?.cancel(); slot.timer?.cancel() } }
    public func issueRequestID() throws -> CapabilityRequestID {
        guard !closed else { throw CapabilityWireError.invalid("host closed") }
        if let index = slots.firstIndex(where: { !$0.reserved && $0.call == nil && $0.generation < generationLimit }) {
            slots[index].generation += 1; slots[index].reserved = true
            return CapabilityRequestID(session: session, slot: UInt16(index), generation: slots[index].generation)
        }
        guard slots.count < capacity else { throw CapabilityWireError.invalid("request quota") }
        slots.append(Slot(generation: 1, reserved: true))
        return CapabilityRequestID(session: session, slot: UInt16(slots.count-1), generation: 1)
    }
    public func submit(_ bytes: Data, deliver: @escaping Delivery) throws {
        guard !closed else { throw CapabilityWireError.invalid("host closed") }
        switch try CapabilityCodec.decodeInbound(bytes) {
        case .cancel(let cancellation):
            let index = try index(cancellation.identity)
            if slots[index].reserved, slots[index].call == nil { slots[index].reserved = false; return }
            guard let call = slots[index].call, call.operation.capabilityID == cancellation.capabilityID,
                  call.operation.operationID == cancellation.operationID else { throw CapabilityWireError.invalid("cancellation owner") }
            terminal(index, outcome: .failure(.cancelled)); slots[index].work?.cancel()
        case .call(let call):
            try accept(call, deliver: deliver, didExit: nil)
        }
    }
    private func accept(_ call: CapabilityCall, deliver: @escaping Delivery, didExit: (@Sendable () -> Void)?) throws {
        let index = try index(call.identity)
        guard slots[index].reserved, slots[index].call == nil else { throw CapabilityWireError.invalid("duplicate call") }
        slots[index].reserved = false; slots[index].call = call; slots[index].delivery = deliver
        let http = self.http, storage = self.storage
        let invoke: @Sendable () async throws -> CapabilityResult
        let returned: @Sendable () -> Void
        #if !os(WASI)
        let lease = installedAdapters.map { _ in CapabilityExitLease { [weak self] lease in
            didExit?()
            Task.detached { [weak self] in await self?.adapterExited(call.identity, lease: lease) }
        } }
        slots[index].exitLease = lease
        if let installedAdapters, let lease {
            invoke = { try await installedAdapters.invoke(call.operation, lease: lease) }
            returned = { lease.invocationReturned() }
        } else {
            invoke = { try Task.checkCancellation(); return try await GeneratedCapabilityDispatch.invoke(call.operation, http: http, storage: storage) }
            returned = {}
        }
        #else
        invoke = { try Task.checkCancellation(); return try await GeneratedCapabilityDispatch.invoke(call.operation, http: http, storage: storage) }
        returned = {}
        #endif
        guard policy.permits(call.operation) else {
            terminal(index, outcome: .failure(.permissionDenied))
            #if !os(WASI)
            if let lease { lease.adapterExited(); lease.invocationReturned() } else { release(index) }
            #else
            release(index)
            #endif
            return
        }
        let timeout: UInt32
        if case .http(let request) = call.operation { timeout = min(request.timeoutMilliseconds, defaultTimeoutMilliseconds) } else { timeout = defaultTimeoutMilliseconds }
        let deadline = ContinuousClock.now.advanced(by: .milliseconds(Int64(timeout)))
        slots[index].deadline = deadline
        slots[index].work = Task.detached { [weak self] in
            defer { returned() }
            let outcome: CapabilityOutcome
            do {
                guard ContinuousClock.now < deadline else {
                    #if !os(WASI)
                    lease?.adapterExited() // No adapter was invoked; join with returned() below.
                    #endif
                    throw CapabilityFailure.deadlineExceeded
                }
                let result = try await invoke()
                if case .http(let response) = result, (300...399).contains(response.status) { throw CapabilityFailure.redirectDenied }
                // Reuse the same strict result path for native callbacks.
                _ = try CapabilityCodec.encodeCompletion(CapabilityCompletion(call: call, outcome: .success(result)))
                outcome = .success(result)
            } catch let failure as CapabilityFailure { outcome = .failure(failure) }
            catch is CancellationError { outcome = .failure(.cancelled) }
            catch is CapabilityWireError { outcome = .failure(.invalidResponse) }
            catch { outcome = .failure(.ioFailure) }
            await self?.complete(call.identity, outcome: outcome)
        }
        slots[index].timer = Task.detached { [weak self] in
            do { try await ContinuousClock().sleep(until: deadline) } catch { return }
            await self?.deadline(call.identity)
        }
    }
    public func close() {
        guard !closed else { return }; closed = true
        for index in slots.indices { if slots[index].call != nil { terminal(index, outcome: .failure(.cancelled)) }; slots[index].work?.cancel(); slots[index].timer?.cancel() }
        slots.removeAll()
    }
    private func index(_ id: CapabilityRequestID) throws -> Int {
        guard id.session == session, Int(id.slot) < slots.count, slots[Int(id.slot)].generation == id.generation,
              slots[Int(id.slot)].reserved || slots[Int(id.slot)].call != nil else { throw CapabilityWireError.invalid("stale request/owner") }
        return Int(id.slot)
    }
    private func terminal(_ index: Int, outcome: CapabilityOutcome) {
        guard !slots[index].terminal, let call = slots[index].call, let delivery = slots[index].delivery else { return }
        slots[index].terminal = true; slots[index].timer?.cancel(); slots[index].delivery = nil
        // Every stored call was decoded and validated; fixed failures always encode.
        if let bytes = try? CapabilityCodec.encodeCompletion(CapabilityCompletion(call: call, outcome: outcome)) { delivery(bytes) }
    }
    private func release(_ index: Int) {
        slots[index].work = nil; slots[index].timer?.cancel(); slots[index].timer = nil; slots[index].call = nil; slots[index].delivery = nil; slots[index].reserved = false; slots[index].terminal = false; slots[index].deadline = nil
        #if !os(WASI)
        slots[index].exitLease = nil
        #endif
    }
    private func complete(_ id: CapabilityRequestID, outcome: CapabilityOutcome) {
        guard !closed, let index = try? index(id), slots[index].call != nil else { return }
        guard let deadline = slots[index].deadline else { return }
        let selected: CapabilityOutcome = ContinuousClock.now >= deadline ? .failure(.deadlineExceeded) : outcome
        terminal(index, outcome: selected)
        #if !os(WASI)
        if slots[index].exitLease != nil { return }
        #endif
        release(index)
    }
    #if !os(WASI)
    private func adapterExited(_ id: CapabilityRequestID, lease: CapabilityExitLease) {
        guard !closed, let index = try? index(id), slots[index].exitLease === lease else { return }
        release(index)
    }
    #endif
    private func deadline(_ id: CapabilityRequestID) {
        guard !closed, let index = try? index(id), slots[index].call != nil else { return }
        guard let deadline = slots[index].deadline, ContinuousClock.now >= deadline else { return }
        terminal(index, outcome: .failure(.deadlineExceeded)); slots[index].work?.cancel()
        // The installed path joins invocation return with adapter resource exit.
        // Legacy closures retain their slot until dispatch returns only.
    }
}

extension CapabilityFailure: Error {}
